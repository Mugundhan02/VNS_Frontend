  visibleNavItems = computed(() => {
    const user = this.auth.currentUser();
    if (!user) return [];
    return this.navItems.filter(item =>
      !item.roles || item.roles.includes(user.role)
    );
  });

  isLoggedIn = computed(() => this.auth.isLoggedIn());

